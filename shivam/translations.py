class Translator:
    """Attribute-style access to translated strings."""

    def __init__(self, lang='en'):
        self.lang = lang if lang in TRANSLATIONS else 'en'
        self._data = TRANSLATIONS[self.lang]
        self._fallback = TRANSLATIONS['en']

    def __getattr__(self, name):
        if name.startswith('_') or name in ('lang', 'get', 'project_status', 'service_category', 'document_type'):
            raise AttributeError(name)
        return self._data.get(name, self._fallback.get(name, name))

    def get(self, name, default=''):
        return self._data.get(name, self._fallback.get(name, default))

    def project_status(self, status_code):
        key = PROJECT_STATUS_KEYS.get(status_code, '')
        return self.get(key, status_code)

    def service_category(self, english_label):
        key = SERVICE_CATEGORY_KEYS.get(english_label, '')
        if key:
            return self.get(key, english_label)
        if self.lang == 'hi':
            from shivam.road_content import SERVICE_CATEGORY_LABELS
            if english_label in SERVICE_CATEGORY_LABELS:
                return SERVICE_CATEGORY_LABELS[english_label][1]
        return english_label

    def document_type(self, type_value):
        key = DOCUMENT_TYPE_KEYS.get(type_value, '')
        return self.get(key, type_value) if key else type_value


def get_translator(lang='en'):
    return Translator(lang)
